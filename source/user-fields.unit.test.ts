import { describe, expect, it } from 'vitest'
import type { Field } from './entities/crm.js'
import { renderUserFields } from './user-fields.js'

const field = (type: string, extra: Partial<Field> = {}): Field => ({
  type,
  isRequired: false,
  isReadOnly: false,
  isImmutable: false,
  isMultiple: false,
  isDynamic: true,
  title: 'UF_CRM_X',
  ...extra
})

const members = (output: string) =>
  output
    .split('\n')
    .filter((line) => line.includes('readonly '))
    .map((line) => line.trim())

describe('renderUserFields', () => {
  it('maps every user field type to the value Bitrix returns', () => {
    const output = renderUserFields(
      {
        deal: {
          ID: field('integer'),
          UF_CRM_STRING: field('string'),
          UF_CRM_URL: field('url'),
          UF_CRM_DATE: field('datetime'),
          UF_CRM_BOOL: field('boolean'),
          UF_CRM_INT: field('integer'),
          UF_CRM_DOUBLE: field('double'),
          UF_CRM_FILE: field('file'),
          UF_CRM_FILES: field('file', { isMultiple: true }),
          UF_CRM_TAGS: field('string', { isMultiple: true }),
          UF_CRM_ENUM: field('enumeration', {
            items: [
              { ID: '45', VALUE: 'One' },
              { ID: '47', VALUE: 'Two' }
            ]
          }),
          UF_CRM_ENUMS: field('enumeration', { isMultiple: true, items: [{ ID: '633', VALUE: 'A' }] }),
          UF_CRM_EMPTY_ENUM: field('enumeration'),
          UF_CRM_APP: field('rest_23_olchat_wa_stats'),
          UF_CRM_APPS: field('rest_1_custom', { isMultiple: true })
        }
      },
      'https://portal.bitrix24.com'
    )

    expect(members(output)).toEqual([
      'readonly UF_CRM_APP: unknown',
      'readonly UF_CRM_APPS: unknown',
      `readonly UF_CRM_BOOL: '0' | '1' | null`,
      'readonly UF_CRM_DATE: string | null',
      'readonly UF_CRM_DOUBLE: number | string | null',
      'readonly UF_CRM_EMPTY_ENUM: string | null',
      `readonly UF_CRM_ENUM: '45' | '47' | null`,
      'readonly UF_CRM_ENUMS: ReadonlyArray<633> | false',
      'readonly UF_CRM_FILE: UserFieldFile | null',
      'readonly UF_CRM_FILES: ReadonlyArray<UserFieldFile> | false',
      'readonly UF_CRM_INT: number | string | null',
      'readonly UF_CRM_STRING: string | null',
      'readonly UF_CRM_TAGS: ReadonlyArray<string> | false',
      'readonly UF_CRM_URL: string | null'
    ])
    expect(output).toContain(`import type { UserFieldFile } from '@2bad/bitrix'`)
  })

  it('renders a module augmentation with labels and enumeration items as comments', () => {
    const output = renderUserFields(
      {
        lead: {
          UF_CRM_SOURCE: field('enumeration', {
            formLabel: 'Lead\nsource',
            items: [{ ID: '1', VALUE: 'Web */ site' }]
          }),
          UF_CRM_NOTE: field('string', { listLabel: 'Note' }),
          UF_CRM_PLAIN: field('string')
        },
        company: {}
      },
      'https://portal.bitrix24.com'
    )

    expect(output)
      .toBe(`// Generated by bitrix-types from https://portal.bitrix24.com. Run it again instead of editing this file.

declare module '@2bad/bitrix' {
  interface LeadUserFields {
    /** Note */
    readonly UF_CRM_NOTE: string | null
    /** UF_CRM_X */
    readonly UF_CRM_PLAIN: string | null
    /**
     * Lead source
     * - 1: Web *\\/ site
     */
    readonly UF_CRM_SOURCE: '1' | null
  }

  interface CompanyUserFields {}
}

export {}
`)
  })

  it('escapes quotes in enumeration ids', () => {
    const output = renderUserFields(
      { deal: { UF_CRM_Q: field('enumeration', { items: [{ ID: "it's", VALUE: 'Quote' }] }) } },
      'https://portal.bitrix24.com'
    )
    expect(members(output)).toEqual([`readonly UF_CRM_Q: 'it\\'s' | null`])
  })
})
