import type { Field, Fields } from './entities/crm.js'

export const USER_FIELD_ENTITIES = {
  deal: 'DealUserFields',
  lead: 'LeadUserFields',
  contact: 'ContactUserFields',
  company: 'CompanyUserFields'
} as const

export type UserFieldEntity = keyof typeof USER_FIELD_ENTITIES

const STRING_TYPES = new Set([
  'string',
  'url',
  'address',
  'money',
  'date',
  'datetime',
  'employee',
  'crm',
  'crm_status',
  'iblock_element',
  'iblock_section'
])

/**
 * Value type as Bitrix returns it in `get` and `list`: enumerations as item ids, strings in single fields
 * and numbers in multiple ones, multiple fields as arrays or `false` when empty
 * @param field field description from `crm.<entity>.fields`
 */
const valueType = (field: Field): { type: string; usesFile: boolean } => {
  const multiple = field.isMultiple
  const items = field.items ?? []
  const single = (() => {
    if (field.type === 'enumeration' && items.length > 0) {
      return items.map(({ ID }) => (multiple ? String(Number(ID)) : `'${ID.replaceAll("'", "\\'")}'`)).join(' | ')
    }
    if (field.type === 'boolean') return `'0' | '1'`
    if (field.type === 'integer' || field.type === 'double') return 'number | string'
    if (field.type === 'file') return 'UserFieldFile'
    if (field.type === 'enumeration' || STRING_TYPES.has(field.type)) return 'string'
    return 'unknown'
  })()
  const usesFile = field.type === 'file'
  if (single === 'unknown') return { type: single, usesFile }
  return multiple ? { type: `ReadonlyArray<${single}> | false`, usesFile } : { type: `${single} | null`, usesFile }
}

const comment = (field: Field, indent: string) => {
  const label = field.formLabel || field.listLabel || field.title
  const lines = [label, ...(field.items ?? []).map(({ ID, VALUE }) => `- ${ID}: ${VALUE}`)].map((line) =>
    line.replaceAll(/\s+/g, ' ').trim().replaceAll('*/', '*\\/')
  )
  return lines.length === 1
    ? `${indent}/** ${lines[0]} */`
    : [`${indent}/**`, ...lines.map((line) => `${indent} * ${line}`), `${indent} */`].join('\n')
}

/**
 * Renders a declaration file that augments the client entity types with the user fields of a portal
 * @param fields `crm.<entity>.fields` results by entity
 * @param origin portal origin for the header, without any token
 */
export const renderUserFields = (fields: Partial<Record<UserFieldEntity, Fields>>, origin: string): string => {
  let usesFile = false
  const interfaces = Object.entries(USER_FIELD_ENTITIES).flatMap(([entity, name]) => {
    const entityFields = fields[entity as UserFieldEntity]
    if (!entityFields) return []
    const members = Object.entries(entityFields)
      .filter(([key]) => key.startsWith('UF_'))
      .toSorted(([a], [b]) => a.localeCompare(b))
      .map(([key, field]) => {
        const value = valueType(field)
        usesFile ||= value.usesFile
        return `${comment(field, '    ')}\n    readonly ${key}: ${value.type}`
      })
    return [members.length === 0 ? `  interface ${name} {}` : `  interface ${name} {\n${members.join('\n')}\n  }`]
  })

  return [
    `// Generated by bitrix-types from ${origin}. Run it again instead of editing this file.`,
    ...(usesFile ? [`import type { UserFieldFile } from '@2bad/bitrix'`] : []),
    '',
    `declare module '@2bad/bitrix' {`,
    interfaces.join('\n\n'),
    '}',
    '',
    'export {}',
    ''
  ].join('\n')
}
